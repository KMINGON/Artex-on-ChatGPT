#!/usr/bin/env node
const assert = require('node:assert/strict');
const { createObservationBuffer, sanitizeObservedURL } = require('./browser-session.cjs');

assert.equal(sanitizeObservedURL('https://user:secret@example.test/api?token=credential#private'), 'https://example.test/api');
assert.equal(sanitizeObservedURL('data:secret'), null);
const buffer = createObservationBuffer(3);
buffer.record('https://example.test/a?token=one', 'GET', 200, 'fetch');
buffer.record('https://example.test/a?token=one', 'GET', 200, 'xhr');
buffer.record('https://example.test/a?token=two', 'GET', 200, 'fetch');
buffer.record('https://example.test/logo.png', 'GET', 200, 'image');
buffer.record('https://example.test/a', 'POST', 201, 'fetch');
const first = buffer.read(0, 1);
assert.equal(first.items.length, 1);
assert.equal(first.items[0].url, 'https://example.test/a?token=one', 'private queue must retain values for query-dependent block rules');
assert.equal(first.has_more, true);
assert.deepEqual(buffer.read(0, 1), first, 'failed downstream save must replay exactly the same observation');
const second = buffer.read(first.cursor, 2, first.epoch);
assert.equal(second.items[0].url, 'https://example.test/a?token=two');
assert.equal(second.items[1].method, 'POST');
buffer.read(second.cursor, 1, first.epoch);
buffer.record('https://example.test/a?token=one', 'GET', 200, 'fetch');
assert.equal(buffer.read(second.cursor).items.length, 0, 'acknowledged duplicate should not be registered again');
for (let i = 0; i < 5; i++) buffer.record(`https://example.test/new-${i}`, 'GET', 200, 'document');
const overflow = buffer.read(second.cursor, 100, first.epoch);
assert.equal(overflow.items.length, 3);
assert.equal(overflow.dropped, 2);
const restarted = createObservationBuffer();
restarted.record('https://example.test/fresh', 'GET', 200, 'document');
assert.equal(restarted.read(999, 100, first.epoch).items.length, 1, 'old process cursor must not acknowledge new process observations');
console.log('PASS: observed HTTP filtering, URL/method deduplication, query gate inputs, cursor retry, bounded overflow');
